package aiss.githubminer.model.github;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonProperty;

import java.util.List;

@JsonIgnoreProperties(ignoreUnknown = true)
public class GHIssue {

    private Long id; // cambiado de Integer a Long
    private Integer number;
    private String title;
    private String body;
    private String state;

    @JsonProperty("created_at")
    private String createdAt;

    @JsonProperty("updated_at")
    private String updatedAt;

    @JsonProperty("closed_at")
    private String closedAt;

    private GHUser user;
    private GHUser assignee;
    private List<Label> labels;

    @JsonProperty("html_url")
    private String htmlUrl;

    // Campo para detectar si es un Pull Request
    @JsonProperty("pull_request")
    private Object pullRequest;

    // Nested Label class
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class Label {
        private String name;

        public String getName() {
            return name;
        }

        public void setName(String name) {
            this.name = name;
        }
    }

    // Getters y setters

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public Integer getNumber() {
        return number;
    }

    public void setNumber(Integer number) {
        this.number = number;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getBody() {
        return body;
    }

    public void setBody(String body) {
        this.body = body;
    }

    public String getState() {
        return state;
    }

    public void setState(String state) {
        this.state = state;
    }

    public String getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(String createdAt) {
        this.createdAt = createdAt;
    }

    public String getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(String updatedAt) {
        this.updatedAt = updatedAt;
    }

    public String getClosedAt() {
        return closedAt;
    }

    public void setClosedAt(String closedAt) {
        this.closedAt = closedAt;
    }

    public GHUser getUser() {
        return user;
    }

    public void setUser(GHUser user) {
        this.user = user;
    }

    public GHUser getAssignee() {
        return assignee;
    }

    public void setAssignee(GHUser assignee) {
        this.assignee = assignee;
    }

    public List<Label> getLabels() {
        return labels;
    }

    public void setLabels(List<Label> labels) {
        this.labels = labels;
    }

    public String getHtmlUrl() {
        return htmlUrl;
    }

    public void setHtmlUrl(String htmlUrl) {
        this.htmlUrl = htmlUrl;
    }

    public Object getPullRequest() {
        return pullRequest;
    }

    public void setPullRequest(Object pullRequest) {
        this.pullRequest = pullRequest;
    }
}
